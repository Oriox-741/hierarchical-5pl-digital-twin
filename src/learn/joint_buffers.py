DQN_REPLAY_STATE_VERSION: Final[str] = "dqn_replay_buffer_v1"


@dataclass(frozen=True, slots=True)
class JointRewardBlendConfig:
    """Role-specific reward blend contract for synchronized PPO/DQN learning."""

    ppo_global_weight: float = 0.35
    ppo_local_weight: float = 0.65
    dqn_local_weight: float = 0.90
    dqn_global_weight: float = 0.10
    dqn_local_health_offset: float = 0.10
    dqn_local_health_scale: float = 0.25

    def __post_init__(self) -> None:
        for name, value in {
            "ppo_global_weight": self.ppo_global_weight,
            "ppo_local_weight": self.ppo_local_weight,
            "dqn_local_weight": self.dqn_local_weight,
            "dqn_global_weight": self.dqn_global_weight,
            "dqn_local_health_offset": self.dqn_local_health_offset,
            "dqn_local_health_scale": self.dqn_local_health_scale,
        }.items():
            _validate_finite_float(name, value)
            if name.endswith("_weight") and value < 0.0:
                raise ValueError(f"{name} must not be negative.")
        if self.ppo_global_weight + self.ppo_local_weight <= 0.0:
            raise ValueError("at least one PPO reward weight must be positive.")
        if self.dqn_local_weight + self.dqn_global_weight <= 0.0:
            raise ValueError("at least one DQN reward weight must be positive.")
        if self.dqn_local_health_scale <= 0.0:
            raise ValueError("dqn_local_health_scale must be positive.")


@dataclass(frozen=True, slots=True)
class JointTransition:
    """Atomic transition generated by one joint PPO+DQN environment step."""

    observation: Tensor
    ppo_action: Tensor
    ppo_log_prob: Tensor
    ppo_value: Tensor
    dqn_action: Tensor
    reward_total: float
    reward_global: float
    reward_ppo_local: float
    reward_dqn_local: float
    reward_ppo_train: float
    reward_dqn_train: float
    next_observation: Tensor
    terminated: bool
    truncated: bool
    projected: bool
    blocked: bool
    info: dict[str, Any] = field(default_factory=dict)
    joint_action_id: str = ""
    episode_id: str = ""
    step_id: int = 0

    @classmethod
    def from_reward_components(
        cls,
        *,
        observation: Tensor,
        ppo_action: Tensor,
        ppo_log_prob: Tensor,
        ppo_value: Tensor,
        dqn_action: Tensor,
        reward_total: float,
        reward_global: float,
        reward_ppo_local: float,
        reward_dqn_local: float,
        reward_blend: JointRewardBlendConfig | None = None,
        next_observation: Tensor,
        terminated: bool,
        truncated: bool,
        projected: bool,
        blocked: bool,
        info: dict[str, Any] | None = None,
        joint_action_id: str = "",
        episode_id: str = "",
        step_id: int = 0,
    ) -> JointTransition:
        for name, value in {
            "reward_total": reward_total,
            "reward_global": reward_global,
            "reward_ppo_local": reward_ppo_local,
            "reward_dqn_local": reward_dqn_local,
        }.items():
            _validate_finite_float(name, value)
        blend = reward_blend or JointRewardBlendConfig()
        reward_ppo_train = ppo_training_reward(
            reward_global=reward_global,
            reward_ppo_local=reward_ppo_local,
            reward_blend=blend,
        )
        reward_dqn_train = dqn_training_reward(
            reward_global=reward_global,
            reward_dqn_local=reward_dqn_local,
            reward_blend=blend,
        )
        return cls(
            observation=observation,
            ppo_action=ppo_action,
            ppo_log_prob=ppo_log_prob,
            ppo_value=ppo_value,
            dqn_action=dqn_action,
            reward_total=reward_total,
            reward_global=reward_global,
            reward_ppo_local=reward_ppo_local,
            reward_dqn_local=reward_dqn_local,
            reward_ppo_train=float(reward_ppo_train),
            reward_dqn_train=float(reward_dqn_train),
            next_observation=next_observation,
            terminated=terminated,
            truncated=truncated,
            projected=projected,
            blocked=blocked,
            info=info or {},
            joint_action_id=joint_action_id,
            episode_id=episode_id,
            step_id=step_id,
        )

    def __post_init__(self) -> None:
        for name, value in {
            "reward_total": self.reward_total,
            "reward_global": self.reward_global,
            "reward_ppo_local": self.reward_ppo_local,
            "reward_dqn_local": self.reward_dqn_local,
            "reward_ppo_train": self.reward_ppo_train,
            "reward_dqn_train": self.reward_dqn_train,
        }.items():
            _validate_finite_float(name, value)

    @property
    def done(self) -> bool:
        return self.terminated or self.truncated

    @property
    def bootstrap_done(self) -> bool:
        return self.terminated


